#!/usr/bin/env node
// Builds the edge block rules from robots.txt, so the edge and robots.txt never drift apart.
//   node edge.mjs cloudflare   → a Cloudflare WAF custom-rule expression (action: Block)
//   node edge.mjs nginx        → a `map` block plus the `if` to put in your server block
//   node edge.mjs middleware   → a Next.js middleware.ts (works on Vercel, Cloudflare and Node)
//   node edge.mjs list         → the user-agent substrings, one per line
// Matching is case-insensitive substring on the User-Agent header. /robots.txt is never blocked, so a blocked bot can
// still read why.
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const tokens = readFileSync(join(here, "..", "robots.txt"), "utf8").split("\n")
  .filter((l) => l.startsWith("User-agent:")).map((l) => l.slice(11).trim());

// Opt-out tokens never crawl, so there is nothing to match at the edge.
const SKIP = new Set(["applebot-extended", "google-extended", "__usage_ai-training"]);
// Names that would match the wrong thing as a bare substring, and the form used instead.
//   "diffbot" would also catch Diffbot-User (a person opening a page), "ccbot" and "yibot" are short,
//   "yak" is in ordinary words, so YaK stays robots.txt-only.
const FORM = { diffbot: "diffbot/", ccbot: "ccbot/", yibot: "yibot/", yak: null };

export function edgeNames() {
  const out = [];
  for (const t of tokens) {
    const k = t.toLowerCase();
    if (SKIP.has(k)) continue;
    const f = k in FORM ? FORM[k] : k;
    if (f) out.push(f);
  }
  // drop names already covered by a shorter one (semrushbot covers semrushbot-ba, webzio covers webzio-extended…)
  const uniq = [...new Set(out)].sort((a, b) => a.length - b.length);
  return uniq.filter((n, i) => !uniq.slice(0, i).some((m) => n.includes(m)));
}

const names = edgeNames();
const mode = process.argv[2] ?? "list";
if (mode === "list") console.log(names.join("\n"));
else if (mode === "cloudflare") {
  console.log(`(http.request.uri.path ne "/robots.txt" and (${names.map((n) => `lower(http.user_agent) contains "${n}"`).join(" or ")}))`);
} else if (mode === "nginx") {
  console.log(`# in the http {} block
map $http_user_agent $botgate_block {
    default 0;
${names.map((n) => `    "~*${n.replace(/[.*+?^${}()|[\]\\]/g, "\\$&").replace(/ /g, "\\s")}" 1;`).join("\n")}
}

# in each server {} block
location = /robots.txt { }  # always readable
if ($botgate_block) { return 403; }`);
} else if (mode === "middleware") {
  console.log(`// middleware.ts (Next.js). Generated by botgate: node skills/botgate/scripts/edge.mjs middleware
import { NextResponse, type NextRequest } from "next/server";

const BLOCK = ${JSON.stringify(names)};

export function middleware(req: NextRequest) {
  if (req.nextUrl.pathname === "/robots.txt") return NextResponse.next();
  const ua = (req.headers.get("user-agent") ?? "").toLowerCase();
  if (BLOCK.some((n) => ua.includes(n))) return new NextResponse("Forbidden", { status: 403 });
  return NextResponse.next();
}

export const config = { matcher: "/:path*" };`);
} else {
  console.error("usage: node edge.mjs cloudflare|nginx|middleware|list");
  process.exit(2);
}
